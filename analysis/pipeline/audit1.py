import pandas as pd, numpy as np, glob, sys
pd.set_option('display.width',250); pd.set_option('display.max_columns',50); pd.set_option('display.max_rows',200)
d=sys.argv[1]
df=pd.concat([pd.read_parquet(p) for p in sorted(glob.glob(d+'/*.parquet'))],ignore_index=True)
df.to_parquet('/home/claude/work/all.parquet',index=False)
print('rows',len(df),'unique id',df.id.nunique())
print(df.dtypes.to_string())
print(df.isna().mean().round(4).to_string())
print(df.state.value_counts(dropna=False).to_string())
fin=df[df.state.isin(['successful','failed'])].copy()
fin['y']=(fin.state=='successful').astype(int)
fin['ly']=pd.to_datetime(fin.launched_at,unit='s').dt.year
print('finished',len(fin),'success',fin.y.mean().round(4))
m=fin.ly.between(2014,2017); print('2014-17',fin[m].y.mean().round(4),m.sum())
print('subcat',fin.subcategory.nunique(),'parent',fin.parent_category.nunique(),'countries',fin.country.nunique())
print('subcat all',df.subcategory.nunique(),df.parent_category.nunique(),df.country.nunique())
print('subcat x parent pairs',fin[['parent_category','subcategory']].drop_duplicates().shape)
print('creators all',df.creator_id.nunique(),'fin',fin.creator_id.nunique())
c=fin.groupby('creator_id').size(); print('creators >1 finished',(c>1).sum())
print('prelaunch known',fin.prelaunch_activated.notna().mean().round(4))
print(fin.prelaunch_activated.value_counts(dropna=False).to_string())
print('--- by launch year'); print(fin.groupby('ly').y.agg(['size','mean']).round(3).to_string())
print('--- all rows by scrape'); 
g=df.groupby('scrape').agg(n=('id','size'),has_video=('has_video',lambda s: pd.to_numeric(s,errors='coerce').mean()),video_na=('has_video',lambda s:s.isna().mean()),prel_known=('prelaunch_activated',lambda s:s.notna().mean()),prel_true=('prelaunch_activated',lambda s: pd.to_numeric(s,errors='coerce').mean()))
print(g.round(3).to_string())
print(df.has_video.value_counts(dropna=False).to_string())
print('--- finished by scrape'); print(fin.groupby('scrape').y.agg(['size','mean']).round(3).to_string())
print('launched_at min/max',pd.to_datetime(df.launched_at.min(),unit='s'),pd.to_datetime(df.launched_at.max(),unit='s'))
print('bad launch (<2009-04)',(df.launched_at<pd.Timestamp('2009-04-01').timestamp()).sum(), 'fin',(fin.launched_at<pd.Timestamp('2009-04-01').timestamp()).sum())
print(df.head(3).T.to_string())
